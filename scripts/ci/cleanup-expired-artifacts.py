#!/usr/bin/env python3
"""Delete regenerable expired artifacts while keeping every project record.

Only paths that are reproducible from a kept input are removed. Each removal is
written to a manifest so the deletion stays auditable.
"""
import argparse
import gzip
import json
import os
from pathlib import Path
import shutil

DEVICE = Path(__file__).resolve().parents[2]
PROJECT = DEVICE.parents[1]

# Regenerable debug text: rewritten by scripts/pack-android-preserving-probe.py
# from the sibling combo.elf. The images, reports and README stay.
DISASSEMBLY = [DEVICE/'out'/f'combo-probe-{index:03d}'/'combo-disassembly.txt'
                for index in range(1, 9)]
# The first data-seed attempt failed (raw APFS mounted as GPT partitions).
# Its guest.log, format.log and seed.json record the failure; the 1 GiB raw
# container is reproducible from prepare-d27-data-linux.py.
FAILED_SEED = DEVICE/'out'/'d27-data-linux-seed-001'/'Data.raw'
# Superseded policy archives; the live one is verified-block-003. The bundle is
# regenerated byte-identically from out/d27-owner-policies-001 by
# build-qemu-source-block.py, so only the copies are removed here.
OLD_POLICIES = [DEVICE/'out'/'d27-qemu-verified-block-001'/'root-policies.bin',
                 DEVICE/'out'/'d27-qemu-verified-block-002'/'root-policies.bin']
# The live policy bundle is referenced by the verified-block-003 symlink and by
# the transport build; it must exist for a rebuild.
LIVE_POLICY = DEVICE/'out'/'d27-qemu-verified-block-002'/'root-policies.bin'
# Smoke-test disk, regenerated by package/Scripts/smoke.sh.
SMOKE_DISK = DEVICE/'out'/'qemu-common-002'/'scenarios'/'gpt-disk.img'
# Downloaded installer archives outside any source tree.
INSTALLERS = [PROJECT/'tmp'/'Microsoft.WSL_3.0.3.0_x64_ARM64.msixbundle']
# Extracted copies of the archives in downloads/; the archives are kept.
EXTRACTED = [PROJECT/'tmp'/'package-ipados17', PROJECT/'tmp'/'package-ios26']
# Oversized compiler logs are compressed in place, keeping every byte.
LOGS = [DEVICE/'out'/'d27-qemu-storage-build-001'/'native-build.log',
        DEVICE/'out'/'qemu-native-threaded-001'/'build.log',
        DEVICE/'out'/'qemu-native-source-001'/'build.log',
        DEVICE/'out'/'qemu-native-source-002'/'build.log',
        DEVICE/'out'/'qemu-native-lto-002'/'build.log',
        DEVICE/'out'/'qemu-native-lto-003'/'build.log']


def size(path):
    total = 0
    for root, _, files in os.walk(path):
        for name in files:
            try:
                total += os.path.getsize(os.path.join(root, name))
            except OSError:
                pass
    return total


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--dry-run', action='store_true')
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=False)
    removed, compressed, kept = [], [], []
    for path in DISASSEMBLY + [FAILED_SEED] + [SMOKE_DISK] + INSTALLERS:
        if not path.exists():
            continue
        if path.is_dir():
            freed = size(path)
            if not args.dry_run:
                shutil.rmtree(path)
            removed.append(dict(path=str(path.relative_to(PROJECT)), bytes=freed, kind='directory'))
        else:
            freed = path.stat().st_size
            if not args.dry_run:
                path.unlink()
            removed.append(dict(path=str(path.relative_to(PROJECT)), bytes=freed, kind='file'))
    for path in EXTRACTED:
        if not path.is_dir():
            continue
        freed = size(path)
        if not args.dry_run:
            shutil.rmtree(path)
        removed.append(dict(path=str(path.relative_to(PROJECT)), bytes=freed, kind='directory'))
    for path in LOGS:
        if not path.is_file():
            continue
        before = path.stat().st_size
        if before < 32 * 2**20:
            continue
        after = before
        if not args.dry_run:
            with path.open('rb') as source, gzip.open(str(path)+'.gz', 'wb', 6) as target:
                shutil.copyfileobj(source, target)
            after = Path(str(path)+'.gz').stat().st_size
            path.unlink()
        compressed.append(dict(path=str(path.relative_to(PROJECT)), bytes=before,
                              compressed_bytes=after, kind='gzip'))
    for path in (PROJECT/'tmp'/'pdx234-root-work-20261110'/'plain',
                 PROJECT/'tmp'/'pdx234-root-work-20261110'/'encrypted',
                 PROJECT/'wsl'/'Ubuntu'/'ext4.vhdx',
                 DEVICE/'out'/'d27-data-linux-seed-002'/'Data.raw',
                 DEVICE/'out'/'d27-userland-original-files-001',
                 DEVICE/'out'/'d27-owner-policies-001',
                 DEVICE/'out'/'d27-cache-index-001',
                 LIVE_POLICY):
        if path.exists():
            kept.append(str(path.relative_to(PROJECT)))
    report = dict(removed=removed, compressed=compressed, kept=kept,
                  freed_bytes=sum(row['bytes'] for row in removed) +
                  sum(row['bytes']-row['compressed_bytes'] for row in compressed),
                  dry_run=args.dry_run,
                  note='Removed paths are reproducible from kept inputs; every report, log, '
                       'evidence file, source tree and original D27 disk stays.')
    (args.out/'cleanup.json').write_text(json.dumps(report, indent=2)+'\n')
    print(json.dumps(dict(removed=len(removed), compressed=len(compressed),
                          freed_gib=round(report['freed_bytes']/2**30, 3),
                          dry_run=args.dry_run), indent=2))


if __name__ == '__main__':
    main()
